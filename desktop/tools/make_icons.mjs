// Regenerates desktop/clubdesk/icondata.py from the Lucide icon set the website
// already ships (public/vendor/lucide-*.min.js, ISC license).
//   node desktop/tools/make_icons.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const vendor = join(here, '..', '..', 'public', 'vendor');
const file = readdirSync(vendor).find(name => /^lucide-.*\.min\.js$/.test(name));
const module = { exports: {} };
new Function('exports', 'module', readFileSync(join(vendor, file), 'utf8'))(module.exports, module);
const icons = module.exports.icons;

// name used by the program -> [Lucide icon, stroke colour]

const attrs = node => Object.entries(node[1]).map(([k, v]) => `${k}="${String(v).replace(/"/g, '&quot;')}"`).join(' ');
const out = ['"""Icon shapes (generated by desktop/tools/make_icons.mjs from Lucide, ISC license). Do not edit."""', '', 'ICONS = {'];
for (const [name, [lucide, colour]] of Object.entries(WANTED)) {
    const node = icons[lucide];
    if (!node) throw new Error(`Lucide has no icon ${lucide}`);
    const body = node.map(child => `<${child[0]} ${attrs(child)}/>`).join('');
    out.push(`    ${JSON.stringify(name)}: (${JSON.stringify(colour)}, ${JSON.stringify(body)}),`);
}
out.push('}', '');
writeFileSync(join(here, '..', 'clubdesk', 'icondata.py'), out.join('\n'));
console.log(`wrote ${Object.keys(WANTED).length} icons`);
